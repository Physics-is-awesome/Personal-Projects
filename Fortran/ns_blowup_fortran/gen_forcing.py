#!/usr/bin/env python3
"""
gen_forcing.py -- generate forcing_gen.f90 (exact collapsing-vortex fields and
the smooth force that makes them an exact solution of forced Navier-Stokes).

Idea (this is the same logic as Sec. 2 of OpenAI's "Finite Time Blowup for
Navier-Stokes", 2026): for ANY divergence-free flow (u,p) one can DEFINE the
force as the momentum residual  f := u_t + (u.grad)u - nu*Lap(u) + grad(p).
The hard part is choosing a blowing-up flow whose residual stays smooth through
the singular time.  Here we only use the leading-order scalings of that flow
(core radius ~ tau^(1/2), core height ~ tau^(1/2-h), swirl and axial speed
~ tau^(-1/2-h), radial speed ~ tau^(-1/2)) with simple Gaussian profiles, so the
residual force produced here is NOT smooth at tau=0 (see README).

Variables (Hou-Li axisymmetric variables, nu = 1):
    u1 = u_theta / r,   om1 = omega_theta / r,   psi1 = psi / r^2
    u_r = -r psi1_z,    u_z = 2 psi1 + r psi1_r,   om1 = -(psi1_rr + 3/r psi1_r + psi1_zz)
    u1_t  + u_r u1_r  + u_z u1_z  - 2 u1 psi1_z = L5 u1  + F1      F1 = f_theta / r
    om1_t + u_r om1_r + u_z om1_z - (u1^2)_z    = L5 om1 + F2      F2 = (curl f)_theta / r
    L5 = d_rr + (3/r) d_r + d_zz
"""
import sympy as sp

r, z, t = sp.symbols('r z t', real=True)
hh, p0, f0, t0, t1 = sp.symbols('hh p0 f0 t0 t1', positive=True)
S0, S1 = sp.symbols('S0 S1')           # switch value and its time derivative
sw = sp.Function('sw')(t)               # smooth switch-on, replaced by S0/S1 below

half = sp.Rational(1, 2)
tau = 1 - t
a = sp.sqrt(tau)                        # core radius   l_r ~ tau^(1/2)
b = tau**(half - hh)                    # core half-height l_z ~ tau^(1/2-h)
rho, zeta = r / a, z / b

# Leading-order amplitudes: psi1 ~ tau^(-1/2-h),  u1 = u_theta/r ~ tau^(-1-h)
psiB = tau**(-half - hh) * p0 * zeta * sp.exp(-rho**2 - zeta**2)
uB = tau**(-1 - hh) * f0 * sp.exp(-rho**2 - zeta**2)

psi1 = sw * psiB
u1 = sw * uB


def L5(f):
    return sp.diff(f, r, 2) + sp.expand(3 / r * sp.diff(f, r)) + sp.diff(f, z, 2)


ur = -r * sp.diff(psi1, z)
uz = 2 * psi1 + r * sp.diff(psi1, r)
om1 = -L5(psi1)

F1 = (sp.diff(u1, t) + ur * sp.diff(u1, r) + uz * sp.diff(u1, z)
      - 2 * u1 * sp.diff(psi1, z) - L5(u1))
F2 = (sp.diff(om1, t) + ur * sp.diff(om1, r) + uz * sp.diff(om1, z)
      - sp.diff(u1**2, z) - L5(om1))


def finish(e):
    e = e.subs(sp.Derivative(sw, t), S1).subs(sw, S0)
    return sp.expand(e)


F1, F2, u1e, psi1e = map(finish, (F1, F2, u1, psi1))
for name, e in (('F1', F1), ('F2', F2)):
    assert not e.has(sp.Function('sw')), name
    # no 1/r left (regularity on the axis)
    assert abs(float(e.subs({r: 1e-12, z: 0.1, t: 0.7, hh: .01, p0: 5, f0: 8, S0: 1, S1: 1}))) < 1e12


def emit(exprs, names):
    """CSE + split into time-only (hoisted) and (r,z)-dependent (in-loop) parts."""
    reps, outs = sp.cse(list(exprs), symbols=sp.numbered_symbols('c'), optimizations='basic')
    dep = {r, z}
    pre, loop = [], []
    for s, e in reps:
        if e.free_symbols & dep:
            dep.add(s)
            loop.append((s, e))
        else:
            pre.append((s, e))
    # outputs that are r,z independent are not expected here
    return pre, loop, outs


def fline(lhs, e, indent):
    code = sp.fcode(e, assign_to=lhs, standard=95, source_format='free', contract=False)
    return '\n'.join(indent + ln for ln in code.splitlines())


def routine(name, args_doc, outs_names, exprs):
    pre, loop, outs = emit(exprs, outs_names)
    temps = sorted({str(s) for s, _ in pre + loop})
    L = []
    L.append(f"  subroutine {name}(nr, nz, rc, zc, t, {', '.join(outs_names)})")
    L.append("    integer, intent(in) :: nr, nz")
    L.append("    real(dp), intent(in) :: rc(nr), zc(nz), t")
    for o in outs_names:
        L.append(f"    real(dp), intent(out) :: {o}(nr, nz)")
    L.append("    real(dp) :: r, z, S0, S1")
    for k in range(0, len(temps), 8):
        L.append("    real(dp) :: " + ', '.join(temps[k:k + 8]))
    L.append("    integer :: i, j")
    L.append("    call switch_fn(t, S0, S1)")
    L.append("    if (S0 == 0.0d0 .and. S1 == 0.0d0) then")
    for o in outs_names:
        L.append(f"      {o} = 0.0d0")
    L.append("      return")
    L.append("    end if")
    for s, e in pre:
        L.append(fline(str(s), e, '    '))
    L.append("    do j = 1, nz")
    L.append("      z = zc(j)")
    L.append("      do i = 1, nr")
    L.append("        r = rc(i)")
    for s, e in loop:
        L.append(fline(str(s), e, '        '))
    for o, e in zip(outs_names, outs):
        L.append(fline(f"{o}(i,j)", e, '        '))
    L.append("      end do")
    L.append("    end do")
    L.append(f"  end subroutine {name}")
    return '\n'.join(L)


src = []
src.append("""! AUTO-GENERATED by gen_forcing.py -- do not edit by hand.
module case_params
  implicit none
  integer, parameter :: dp = kind(1.0d0)
  ! hh : anisotropy exponent h (paper: 0 < h < 1/100); l_r ~ tau^(1/2), l_z ~ tau^(1/2-h)
  ! p0 : amplitude of the meridional (inflow/outflow) stream function
  ! f0 : amplitude of the swirl
  ! t0,t1 : the flow is exactly at rest for t<=t0 and the force switches on smoothly over [t0,t1]
  real(dp) :: hh = 0.01d0, p0 = 5.0d0, f0 = 8.0d0, t0 = 0.3d0, t1 = 0.5d0
end module case_params

module forcing_gen
  use case_params
  implicit none
contains

  subroutine switch_fn(t, s, ds)
    ! C-infinity step: 0 for t<=t0, 1 for t>=t1.  ds = ds/dt.
    real(dp), intent(in) :: t
    real(dp), intent(out) :: s, ds
    real(dp) :: x, A, B, dA, dB
    x = (t - t0) / (t1 - t0)
    if (x <= 0.0d0) then
      s = 0.0d0; ds = 0.0d0
    else if (x >= 1.0d0) then
      s = 1.0d0; ds = 0.0d0
    else
      A = exp(-1.0d0 / x);          dA = A / x**2
      B = exp(-1.0d0 / (1.0d0-x));  dB = B / (1.0d0-x)**2
      s  = A / (A + B)
      ds = (dA * B + A * dB) / (A + B)**2 / (t1 - t0)
    end if
  end subroutine switch_fn
""")
src.append(routine('eval_exact', '', ['u1', 'psi1'], [u1e, psi1e]))
src.append("")
src.append(routine('eval_force', '', ['F1', 'F2'], [F1, F2]))
src.append("\nend module forcing_gen\n")

with open('forcing_gen.f90', 'w') as fh:
    fh.write('\n'.join(src))
print('wrote forcing_gen.f90')
